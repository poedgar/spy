// Flat arrays for quick reference
export const SPY_LOCATIONS: string[] = SPY_LOCATIONS_DATA.map((l) => l.en);
export const SPY_LOCATIONS_UK: string[] = SPY_LOCATIONS_DATA.map((l) => l.uk);

// Fast lookup map: English -> Ukrainian & Ukrainian -> English
const EN_TO_UK_MAP: Record<string, string> = {};
const UK_TO_EN_MAP: Record<string, string> = {};

SPY_LOCATIONS_DATA.forEach((loc) => {
  EN_TO_UK_MAP[loc.en.toLowerCase()] = loc.uk;
  UK_TO_EN_MAP[loc.uk.toLowerCase()] = loc.en;
});

/**
 * Returns translated name of a location in the requested language
 */
export function getLocationName(location: string, lang: 'en' | 'uk' = 'en'): string {
  if (!location) return '';
  const lower = location.trim().toLowerCase();

  if (lang === 'uk') {
    if (EN_TO_UK_MAP[lower]) return EN_TO_UK_MAP[lower];
    // Check if it's already Ukrainian
    const item = SPY_LOCATIONS_DATA.find((l) => l.uk.toLowerCase() === lower);
    if (item) return item.uk;
    return location;
  }

  // lang === 'en'
  if (UK_TO_EN_MAP[lower]) return UK_TO_EN_MAP[lower];
  // Check if it's already English
  const item = SPY_LOCATIONS_DATA.find((l) => l.en.toLowerCase() === lower);
  if (item) return item.en;
  return location;
}

/**
 * Returns random location from the 500 pool in requested language
 */
export function getRandomLocation(lang: 'en' | 'uk' = 'en'): string {
  const index = Math.floor(Math.random() * SPY_LOCATIONS_DATA.length);
  return lang === 'uk' ? SPY_LOCATIONS_DATA[index].uk : SPY_LOCATIONS_DATA[index].en;
}

/**
 * Search locations across both English and Ukrainian terms
 */
export function searchLocations(query: string): SpyLocation[] {
  if (!query || !query.trim()) return SPY_LOCATIONS_DATA;
  const term = query.trim().toLowerCase();
  return SPY_LOCATIONS_DATA.filter(
    (loc) =>
      loc.en.toLowerCase().includes(term) ||
      loc.uk.toLowerCase().includes(term) ||
      loc.category.toLowerCase().includes(term)
  );
}
